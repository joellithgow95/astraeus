/**
 * An icon as an SVG element.
 *
 * Decorative by default (aria-hidden): the control around it carries the
 * accessible name. An unknown name draws the plain file glyph rather than
 * nothing, so a typo shows up as the wrong icon, not a hole in the layout.
 *
 * @param {string} name
 * @param {{size?: number, class?: string}} [opts]
 * @returns {SVGSVGElement}
 */
export function icon(name, opts = {}) {
  const size = opts.size ?? 16
  const tpl = document.createElement('template')
  tpl.innerHTML =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false" class="icon${opts.class ? ` ${opts.class}` : ''}" data-icon="${name}">` +
    `${PATHS[name] || PATHS.file}</svg>`
  return /** @type {SVGSVGElement} */ (tpl.content.firstElementChild)
}

/** Whether the set has a glyph by this name. */
export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(PATHS, name)
}

/**
 * Words in a type key, matched in order, mapped to a glyph. More specific
 * words come first: "project_page" is a project before it is a page.
 */
const TYPE_RULES = [
  [['blog', 'post', 'article', 'note'], 'pen'],
  [['project', 'case_study', 'portfolio'], 'folder'],
  [['experience', 'job', 'role', 'resume', 'work'], 'briefcase'],
  [['definition', 'dictionary', 'glossary', 'term'], 'book'],
  [['link', 'bookmark'], 'bookmark'],
  [['spotify', 'music', 'song', 'track', 'album', 'playlist'], 'music'],
  [['inat', 'observation', 'nature', 'species', 'plant', 'bird'], 'leaf'],
  [['prompt', 'system'], 'terminal'],
  [['model', 'config', 'setting'], 'sliders'],
  [['user', 'author', 'person', 'people', 'member'], 'user'],
  [['category', 'tag', 'topic'], 'tag'],
  [['media', 'image', 'photo', 'asset', 'gallery'], 'image'],
  [['event', 'calendar', 'date'], 'calendar'],
  [['product', 'item', 'inventory'], 'box'],
  [['page'], 'file-text'],
]

/**
 * The glyph for a document type: the schema's `icon` when it names one in
 * this set, else a match on the words in the type key, else a plain file.
 *
 * @param {string} typeKey
 * @param {object} [typeInfo] — the type's entry in the editor schema
 * @returns {string}
 */
export function typeIconName(typeKey, typeInfo) {
  if (typeInfo?.icon && hasIcon(typeInfo.icon)) return typeInfo.icon
  const key = typeKey.toLowerCase()
  for (const [words, name] of TYPE_RULES) {
    if (words.some(w => key.includes(w))) return name
  }
  return 'file'
}
